#include "network-capture/importer/importer_utils.hpp"

#include "network-capture/datatypes/protocol.hpp"

Protocol
convert_protocol_type(const pcpp::ProtocolType& p_type)
{
    switch (p_type) {
        case pcpp::UnknownProtocol:
            return Protocol::UnknownProtocol;
        case pcpp::Ethernet:
            return Protocol::Ethernet;
        case pcpp::IPv4:
            return Protocol::IPv4;
        case pcpp::IPv6:
            return Protocol::IPv6;
        case pcpp::TCP:
            return Protocol::TCP;
        case pcpp::UDP:
            return Protocol::UDP;
        case pcpp::HTTPRequest:
            return Protocol::HTTPRequest;
        case pcpp::HTTPResponse:
            return Protocol::HTTPResponse;
        case pcpp::ARP:
            return Protocol::ARP;
        case pcpp::VLAN:
            return Protocol::VLAN;
        case pcpp::ICMP:
            return Protocol::ICMP;
        case pcpp::PPPoESession:
            return Protocol::PPPoESession;
        case pcpp::PPPoEDiscovery:
            return Protocol::PPPoEDiscovery;
        case pcpp::DNS:
            return Protocol::DNS;
        case pcpp::MPLS:
            return Protocol::MPLS;
        case pcpp::GREv0:
            return Protocol::GREv0;
        case pcpp::GREv1:
            return Protocol::GREv1;
        case pcpp::PPP_PPTP:
            return Protocol::PPP_PPTP;
        case pcpp::SSL:
            return Protocol::SSL;
        case pcpp::SLL:
            return Protocol::SLL;
        case pcpp::DHCP:
            return Protocol::DHCP;
        case pcpp::NULL_LOOPBACK:
            return Protocol::NULL_LOOPBACK;
        case pcpp::IGMPv1:
            return Protocol::IGMPv1;
        case pcpp::IGMPv2:
            return Protocol::IGMPv2;
        case pcpp::IGMPv3:
            return Protocol::IGMPv3;
        case pcpp::GenericPayload:
            return Protocol::GenericPayload;
        case pcpp::VXLAN:
            return Protocol::VXLAN;
        case pcpp::SIPRequest:
            return Protocol::SIPRequest;
        case pcpp::SIPResponse:
            return Protocol::SIPResponse;
        case pcpp::SDP:
            return Protocol::SDP;
        case pcpp::PacketTrailer:
            return Protocol::PacketTrailer;
        case pcpp::Radius:
            return Protocol::Radius;
        case pcpp::GTPv1:
            return Protocol::GTPv1;
        case pcpp::EthernetDot3:
            return Protocol::EthernetDot3;
        case pcpp::BGP:
            return Protocol::BGP;
        case pcpp::SSH:
            return Protocol::SSH;
        case pcpp::AuthenticationHeader:
            return Protocol::AuthenticationHeader;
        case pcpp::ESP:
            return Protocol::ESP;
        case pcpp::DHCPv6:
            return Protocol::DHCPv6;
        case pcpp::NTP:
            return Protocol::NTP;
        case pcpp::Telnet:
            return Protocol::Telnet;
        case pcpp::FTP:
            return Protocol::FTP;
        case pcpp::ICMPv6:
            return Protocol::ICMPv6;
        case pcpp::STP:
            return Protocol::STP;
        case pcpp::LLC:
            return Protocol::LLC;
        case pcpp::SomeIP:
            return Protocol::SomeIP;
        case pcpp::WakeOnLan:
            return Protocol::WakeOnLan;
        case pcpp::NFLOG:
            return Protocol::NFLOG;
        case pcpp::TPKT:
            return Protocol::TPKT;
        case pcpp::VRRPv2:
            return Protocol::VRRPv2;
        case pcpp::VRRPv3:
            return Protocol::VRRPv3;
        case pcpp::COTP:
            return Protocol::COTP;
        case pcpp::SLL2:
            return Protocol::SLL2;
        case pcpp::S7COMM:
            return Protocol::S7COMM;
        case pcpp::SMTP:
            return Protocol::SMTP;
        case pcpp::PROFINET_RT:
            return Protocol::PROFINET_RT;
        case pcpp::PROFINET_RT_DCP:
            return Protocol::PROFINET_RT_DCP;
        case pcpp::PROFINET_RT_IO:
            return Protocol::PROFINET_RT_IO;
        case pcpp::PROFINET_RT_PTCP:
            return Protocol::PROFINET_RT_PTCP;
        case pcpp::PROFINET_DCE_RPC:
            return Protocol::PROFINET_DCE_RPC;
        case pcpp::LLDP:
            return Protocol::LLDP;
        case pcpp::OPC_UA:
            return Protocol::OPC_UA;
        case pcpp::NetBIOS:
            return Protocol::NetBIOS;
        case pcpp::SSDP:
            return Protocol::SSDP;
        case pcpp::Syslog:
            return Protocol::Syslog;
        default:
            return Protocol::UnknownProtocol;
    }
}
